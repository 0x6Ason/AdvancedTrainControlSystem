package dev.advancedtrains.atcs.command;

import dev.advancedtrains.atcs.control.StopOptions;
import dev.advancedtrains.atcs.control.SwitchRules;
import org.bukkit.configuration.ConfigurationSection;
import org.bukkit.configuration.file.YamlConfiguration;

import java.io.IOException;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.logging.Logger;

/**
 * Writes the reference pages under {@code docs/reference/} from the code itself: the command tree,
 * the sign kinds and their options, {@code plugin.yml}'s permissions and the bundled
 * {@code config.yml}. {@code ./gradlew generateDocs} runs it; {@link ReferenceDocsTest} fails when
 * the committed pages differ from what it would write, so the reference cannot drift.
 */
public final class ReferenceDocs {
    private static final String GENERATED = "<!-- Generated by ./gradlew generateDocs from the plugin's code; do not edit by hand. -->\n\n";

    private ReferenceDocs() {
    }

    public static void main(String[] args) throws IOException {
        Path directory = Path.of(args.length > 0 ? args[0] : "docs/reference");
        Files.createDirectories(directory);
        for (Map.Entry<String, String> page : pages().entrySet()) {
            Files.writeString(directory.resolve(page.getKey()), page.getValue(), StandardCharsets.UTF_8);
            System.out.println("wrote " + directory.resolve(page.getKey()));
        }
    }

    /** File name to Markdown text, in a stable order. */
    public static Map<String, String> pages() throws IOException {
        Map<String, String> pages = new LinkedHashMap<>();
        pages.put("commands.md", commands());
        pages.put("signs.md", signs());
        pages.put("permissions.md", permissions());
        pages.put("config.md", config());
        return pages;
    }

    // ---------------------------------------------------------------- commands

    static String commands() {
        AtcsCommand command = new AtcsCommand(new Support(null, null, null, null, null, null, null, null), Logger.getLogger("atcs-docs"));
        StringBuilder text = new StringBuilder(GENERATED);
        text.append("# Commands\n\n");
        text.append("Every command starts with `/atcs` (alias `/traincontrol`). `/atcs help` and `/atcs <group> help` list what you may use. ");
        text.append("Arguments in angle brackets are required, in square brackets optional; `...` takes the rest of the line.\n\n");
        text.append("| Permission | Who has it by default |\n|---|---|\n");
        text.append("| `").append(Support.USE).append("` | everyone |\n");
        text.append("| `").append(Support.MANAGE).append("` | operators |\n\n");
        Node.Group root = command.root();
        text.append("## /atcs\n\n");
        text.append(root.description).append("\n\n");
        table(text, "/atcs", root, false);
        for (Node child : root.children().values()) {
            if (child instanceof Node.Group group) {
                text.append("## /atcs ").append(group.name).append("\n\n");
                text.append(group.description).append(".\n\n");
                table(text, "/atcs " + group.name, group, true);
            }
        }
        return text.toString();
    }

    private static void table(StringBuilder text, String path, Node.Group group, boolean nested) {
        text.append("| Command | Permission | |\n|---|---|---|\n");
        for (Node child : group.children().values()) {
            if (child instanceof Node.Group) {
                if (!nested) {
                    text.append("| `").append(path).append(' ').append(child.name).append(" ...` | `")
                            .append(child.permission).append("` | ").append(child.description)
                            .append(" (see below) |\n");
                }
                continue;
            }
            String usage = child.usage.isEmpty() ? "" : " " + child.usage;
            text.append("| `").append(escape(path + " " + child.name + usage)).append("` | `")
                    .append(child.permission).append("` | ").append(escape(child.description)).append(" |\n");
        }
        text.append('\n');
    }

    // ---------------------------------------------------------------- signs

    static String signs() {
        StringBuilder text = new StringBuilder(GENERATED);
        text.append("# Signs reference\n\n");
        text.append("Every ATCS sign is a TrainCarts sign. Line 1 is `[+train]` (always on) or `[train]` (acts only while powered by redstone); ");
        text.append("line 2 names the kind. Building one needs the `atcs.sign.build` permission. Kinds and their other names:\n\n");
        text.append("| Line 2 | Line 3 | Line 4 | Does |\n|---|---|---|---|\n");
        List<String[]> kinds = List.of(
                new String[] {"atcs stop` (`platform`)", "`station` or `station:platform`", "platform (default `1`)",
                        "marks a platform without binding a sign in network.yml; only watches"},
                new String[] {"atcs station` (`halt`)", "`station` or `station:platform`", "options, see below",
                        "a platform that stops the trains whose service calls there and lets the others run through"},
                new String[] {"atcs switch` (`switcher`, `junction`)", "a rule", "a rule (more on signs below)",
                        "sets the junction it sits on per train, by service, line or next station"},
                new String[] {"atcs service` (`assign`)", "`line/service`", "", "assigns passing trains to the service"},
                new String[] {"atcs clear` (`unassign`)", "", "", "removes the assignment of passing trains"},
                new String[] {"atcs indicator` (`lamp`)", "`station` or `station:platform`, or `block <id>`", "mode and filter, see below",
                        "drives the levers on its block while trains are at, approaching or past the station, or inside a block"},
                new String[] {"atcs block` (`signal`)", "the block's id", "`enter` or `exit`",
                        "one train at a time between the entry and exit signs; a train reaching the entry while another is inside waits there"},
                new String[] {"atcs speed` (`limit`)", "blocks per tick, for example `0.6`", "a line, `line/service` or nothing",
                        "sets the speed limit of passing trains, all or the named line's or service's"});
        for (String[] kind : kinds) {
            text.append("| `").append(kind[0]).append(" | ").append(kind[1]).append(" | ").append(kind[2])
                    .append(" | ").append(kind[3]).append(" |\n");
        }
        text.append("\n## Station sign options (line 4)\n\n");
        text.append("Any order, every part optional. In the plugin's words: ").append(StopOptions.HELP).append(".\n\n");
        text.append("| Option | Meaning |\n|---|---|\n");
        text.append("| `10s` or `10` | dwell time in seconds; without one, `control.dwell-seconds` |\n");
        text.append("| `continue`, `reverse`, `left`, `right`, `north`, `east`, `south`, `west` | where the train goes afterwards; `continue` when left out |\n");
        text.append("| `route` | TrainCarts path-finding picks the direction from the train's destination |\n");
        text.append("| `2.5m` | centre the train 2.5 blocks past the sign (`-2.5m`: before it) |\n");
        text.append("| `30b` | launch the train over 30 blocks |\n");
        text.append("| `0.4v` | launch at 0.4 blocks per tick instead of TrainCarts' default |\n");
        text.append("| `gap 60s` | headway: do not leave until 60 s after the last train of the same line left this platform; `gap 0` switches a configured headway off |\n");
        text.append("| `block` / `noblock` | wait until the train that left before has reached its next station, or never |\n");
        text.append("| `even` / `noeven` | hold a train that is catching up the one in front so the service's trains spread out, at most `control.even-max-hold-seconds` |\n");
        text.append("| `at :00 :30`, `at /15` | leave at these minutes past the hour, or every 15 minutes, by the server's clock |\n\n");
        text.append("Which trains stop: the service calls at the station, stop; the service runs through (`~station`) or does not list it, pass; ");
        text.append("no service, `control.unknown-trains`; the service does not list the station, `control.off-route-trains`.\n\n");
        text.append("## Switch sign rules (lines 3, 4 and signs below)\n\n");
        text.append("In the plugin's words: ").append(SwitchRules.HELP).append(". The first rule that fits wins; ");
        text.append("a train no rule fits leaves the junction as it is. `*` (or `all`, `any`) means every train, and a direction on its own means the same. ");
        text.append("`continue` and `reverse` follow the train; `left` and `right` are as seen by a train driving into the front of the sign.\n\n");
        text.append("## Indicator modes (line 4)\n\n");
        text.append("| Line 4 | On while |\n|---|---|\n");
        text.append("| empty or `at` (`here`, `standing`) | a train stands at (or runs through) the station or platform |\n");
        text.append("| `approach` (`approaching`, `arriving`) | a train has been announced as approaching it |\n");
        text.append("| `after` (`leaving`, `left`, `from`) | a train has left it and has not reached its next stop |\n");
        text.append("| `to <station>` (`towards`) | a train has left it and the other station is its next stop |\n");
        text.append("| `between <station>` (`with`) | a train runs between the two stations, in either direction |\n");
        text.append("| line 3 `block <id>` | a train is inside the virtual block of that name |\n\n");
        text.append("A line id (`5`) or a service (`5/cw`) after the mode counts only those trains.\n");
        return text.toString();
    }

    // ---------------------------------------------------------------- permissions

    static String permissions() throws IOException {
        YamlConfiguration plugin = YamlConfiguration.loadConfiguration(new StringReader(
                Files.readString(Path.of("src/main/resources/plugin.yml"), StandardCharsets.UTF_8)));
        StringBuilder text = new StringBuilder(GENERATED);
        text.append("# Permissions\n\n| Permission | Default | Grants |\n|---|---|---|\n");
        ConfigurationSection permissions = plugin.getConfigurationSection("permissions");
        if (permissions != null) {
            for (String name : permissions.getKeys(false)) {
                ConfigurationSection permission = permissions.getConfigurationSection(name);
                if (permission == null) {
                    continue;
                }
                String grants = permission.getString("description", "");
                ConfigurationSection children = permission.getConfigurationSection("children");
                if (children != null) {
                    grants += " Includes " + String.join(", ", children.getKeys(false).stream().map(child -> "`" + child + "`").toList()) + ".";
                }
                text.append("| `").append(name).append("` | ").append(permission.getString("default", "op"))
                        .append(" | ").append(grants).append(" |\n");
            }
        }
        return text.toString();
    }

    // ---------------------------------------------------------------- config

    static String config() throws IOException {
        String config = Files.readString(Path.of("src/main/resources/config.yml"), StandardCharsets.UTF_8).replace("\r\n", "\n");
        return GENERATED + "# config.yml\n\nThe file as the plugin writes it on first start, with every setting explained in place. "
                + "Apply changes with `/atcs reload`.\n\n```yaml\n" + config + (config.endsWith("\n") ? "" : "\n") + "```\n";
    }

    private static String escape(String text) {
        return text.replace("|", "\\|");
    }
}
